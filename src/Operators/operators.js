console.log("==  (Equal to)");
console.log(5 == "5");      // true

console.log("\n=== (Strict Equal)");
console.log(5 === "5");     // false

console.log("\n!=  (Not Equal)");
console.log(5 != 6);        // true

console.log("\n!== (Strict Not Equal)");
console.log(5 !== "5");     // true

