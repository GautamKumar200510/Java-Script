console.log(10 > 5);        // true

console.log("\n<   (Less Than)");
console.log(5 < 10);        // true

console.log("\n>=  (Greater Than or Equal)");
console.log(10 >= 10);      // true

console.log("\n<=  (Less Than or Equal)");
console.log(5 <= 10);       // true